import java.io.File
import java.util.concurrent.Callable
import java.util.concurrent.Executors

/**
 * Run-level simulation (docs/09 "Testing and QA"): whole runs of The First Hour, all three acts, played by [RunBot]
 * (the planner in fights, heuristics between them), many seeds per operative. Deterministic for a given seed count.
 *
 * Usage: sim --runs N [--threads N] [--ops oracle,splinter] [--out FILE]
 *        sim --replay "r2 vowknight 1234 london_1843 c0 P/12//// ..."   (a run code copied from the web client)
 */
fun runSim(opts: Map<String, String>) {
    val runs = opts["runs"]!!.toInt()
    val threads = opts["threads"]?.toInt() ?: Runtime.getRuntime().availableProcessors()
    val re = RunEngine(FirstHour.run)
    val ops = operatives(opts, re.content.operatives.keys)
    val started = System.nanoTime()
    val pool = Executors.newFixedThreadPool(threads)
    val results = try {
        val jobs = ops.flatMap { op -> (1..runs).map { i -> Callable { op to RunRunner.play(re, op, runSeed(op, i), RunBot(runSeed(op, i))).first } } }
        pool.invokeAll(jobs).map { it.get() }
    } finally {
        pool.shutdown()
    }
    val seconds = (System.nanoTime() - started) / 1e9
    val report = RunReport(re, results.groupBy({ it.first }, { it.second }), runs).render()
    val out = opts["out"]
    if (out != null) {
        File(out).absoluteFile.parentFile.mkdirs()
        File(out).writeText(report)
        println("Wrote $out (${results.size} runs in ${"%.1f".format(seconds)} s on $threads threads)")
    } else {
        println(report)
        System.err.println("${results.size} runs in ${"%.1f".format(seconds)} s on $threads threads")
    }
}

/** Plays run [index] of [op] as `--runs` would, then prints its replay code and full log: `--run-trace op/index`. */
fun traceRun(spec: String) {
    val (op, index) = spec.split("/")
    val re = RunEngine(FirstHour.run)
    val seed = runSeed(op, index.toInt())
    val (_, actions) = RunRunner.play(re, op, seed, RunBot(seed))
    val code = RunReplay(op, seed, re.rc.eras.first().id, actions).encode()
    println("Replay: $code")
    replayRun(code)
}

/** Replays a run code and prints its log. */
fun replayRun(code: String) {
    val re = RunEngine(FirstHour.run)
    val r = RunReplay.parse(code.substringAfter("Replay:").trim())
    var out = re.start(r.operative, r.seed, r.era)
    out.log.forEach { println(it) }
    for ((i, a) in r.actions.withIndex()) {
        val next = re.apply(out.state, a)
        if (next.error != null) {
            println("Action ${i + 1} (${RunReplay.encode(a)}) was rejected: ${next.error}")
            return
        }
        next.log.forEach { println(it) }
        next.events.forEach { println("  " + it.text) }
        out = next
    }
    val s = out.state
    println("State: ${s.screen::class.simpleName}, act ${s.act} step ${s.step}, HP ${s.hp}/${s.maxHp}, level ${s.level}, Hours ${s.hours}, Paradox ${s.paradox}, deck ${s.deck.size}")
}

private fun runSeed(op: String, i: Int): Long {
    var h = 1469598103934665603L
    for (ch in "run/$op") h = (h xor ch.code.toLong()) * 1099511628211L
    return (h and 0x7fffffffffffL) + i
}

private class RunReport(val re: RunEngine, val byOp: Map<String, List<RunState>>, val runs: Int) {
    private val content = re.content
    private val acts = re.rc.eras
    private fun pct(x: Double) = if (x.isNaN()) "–" else "%.0f%%".format(100 * x)
    private fun num(x: Double, d: Int = 1) = if (x.isNaN()) "–" else "%.${d}f".format(x)
    private fun List<Double>.avg() = if (isEmpty()) Double.NaN else average()
    private fun name(op: String) = content.operative(op).name
    private fun won(s: RunState) = (s.screen as? Screen.Over)?.won == true
    private fun reached(s: RunState, act: Int) = s.stats.acts.any { it.act == act }
    private fun bossOf(s: RunState, act: Int) = s.stats.fightRecords.firstOrNull { it.act == act && it.type == MomentType.BOSS }

    /** Encounter names, with the id where two encounters share a name (the Automa Cavaliere's hearts). */
    private fun encName(id: String): String {
        val n = content.encounter(id).name
        return if (content.encounters.count { it.name == n } > 1) "$n ($id)" else n
    }

    fun render(): String = buildString {
        val total = byOp.values.sumOf { it.size }
        appendLine("# Run simulation: The First Hour")
        appendLine()
        appendLine("$total runs ($runs per operative) of all three acts, played by the run bot: the planner in every fight, simple")
        appendLine("heuristics between fights (it never Glimpses, reads Omens only to look at Elites, and always Rewinds when it")
        appendLine("falls with its Anchor unspent). Generated by `./gradlew :sim:run --args=\"--runs $runs --out reports/run-latest.md\"`.")
        appendLine("Deterministic: rerunning gives the same report.")
        appendLine()

        appendLine("## Outcomes")
        appendLine()
        appendLine("How far runs got. A boss's column counts the runs that fought it and how many of those got past it (Rewinding")
        appendLine("and winning a rematch counts).")
        appendLine()
        val bossCols = acts.joinToString(" | ") { "Act ${it.act} boss" }
        appendLine("| Operative | Won the run | " + acts.drop(1).joinToString(" | ") { "Reached Act ${it.act}" } + " | $bossCols |")
        appendLine("|---|---|" + acts.drop(1).joinToString("") { "---|" } + acts.joinToString("") { "---|" })
        for ((op, states) in byOp) {
            val reach = acts.drop(1).joinToString(" | ") { a -> pct(states.count { reached(it, a.act) }.toDouble() / states.size) }
            val bosses = acts.joinToString(" | ") { a ->
                val fought = states.filter { bossOf(it, a.act) != null }
                val beat = fought.count { s -> s.stats.fightRecords.any { it.act == a.act && it.type == MomentType.BOSS && it.won } }
                if (fought.isEmpty()) "–" else "${pct(beat.toDouble() / fought.size)} of ${fought.size}"
            }
            appendLine("| ${name(op)} | ${pct(states.count { won(it) }.toDouble() / states.size)} | $reach | $bosses |")
        }
        appendLine()
        appendLine("Where runs ended:")
        appendLine()
        appendLine("| Operative | " + acts.joinToString(" | ") { "Act ${it.act}, before the boss | Act ${it.act} boss" } + " | Won |")
        appendLine("|---|" + acts.joinToString("") { "---|---|" } + "---|")
        for ((op, states) in byOp) {
            val cells = acts.joinToString(" | ") { a ->
                val inAct = states.filter { !won(it) && it.act == a.act }
                val atBoss = inAct.count { s -> s.stats.fightRecords.lastOrNull()?.let { it.type == MomentType.BOSS && !it.won } == true }
                "${pct((inAct.size - atBoss).toDouble() / states.size)} | ${pct(atBoss.toDouble() / states.size)}"
            }
            appendLine("| ${name(op)} | $cells | ${pct(states.count { won(it) }.toDouble() / states.size)} |")
        }
        appendLine()

        appendLine("## Trajectory")
        appendLine()
        appendLine("The run as each act began (averages over the runs that got there), and how its boss went.")
        appendLine()
        appendLine("| Operative | Act | Runs | HP | Max HP | Deck | Level | Artifacts | Paradox | Hours | HP entering the boss | Boss HP lost (wins) |")
        appendLine("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for ((op, states) in byOp) {
            for (a in acts) {
                val recs = states.mapNotNull { s -> s.stats.acts.lastOrNull { it.act == a.act } }
                if (recs.isEmpty()) continue
                fun avg(f: (dcbb.core.run.ActRecord) -> Number) = num(recs.map { f(it).toDouble() }.avg())
                val bosses = states.mapNotNull { bossOf(it, a.act) }
                val wins = bosses.filter { it.won }
                appendLine(
                    "| ${name(op)} | ${a.act} | ${recs.size} | ${pct(recs.map { it.hp.toDouble() / it.maxHp }.avg())} | ${avg { it.maxHp }} | ${avg { it.deck }} | " +
                        "${avg { it.level }} | ${avg { it.artifacts }} | ${avg { it.paradox }} | ${avg { it.hours }} | " +
                        "${pct(bosses.map { it.hpBefore.toDouble() / it.maxHp }.avg())} | ${pct(wins.map { (it.hpBefore - it.hpAfter).toDouble() / it.maxHp }.avg())} |",
                )
            }
        }
        appendLine()
        appendLine("At the end of the run (wins and losses together):")
        appendLine()
        appendLine("| Operative | Level | Deck | Artifacts | Fights | Elites | Cards taken | Erased | Inscribed | Hours earned | Omens read | Paradox peak |")
        appendLine("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for ((op, states) in byOp) {
            fun a(f: (RunState) -> Number) = num(states.map { f(it).toDouble() }.avg())
            appendLine(
                "| ${name(op)} | ${a { it.level }} | ${a { it.deck.size }} | ${a { it.artifacts.size }} | ${a { it.stats.fights }} | ${a { it.stats.elites }} | " +
                    "${a { it.stats.cardsTaken }} | ${a { it.stats.erased }} | ${a { it.stats.inscribed }} | ${a { it.stats.hoursEarned }} | " +
                    "${a { it.stats.omensRead }} | ${a { it.stats.paradoxPeak }} |",
            )
        }
        appendLine()

        appendLine("## Fights by act and kind")
        appendLine()
        appendLine("Share of max HP lost per fight, and how many of those fights ended the run (after any Rewind).")
        appendLine()
        appendLine("| Operative | Act | Threat 1 | Threat 2 | Threat 3 | Elite | Boss |")
        appendLine("|---|---|---|---|---|---|---|")
        for ((op, states) in byOp) {
            val records = states.flatMap { it.stats.fightRecords }
            for (a in acts) {
                val rs = records.filter { it.act == a.act }
                if (rs.isEmpty()) continue
                fun cell(sel: (dcbb.core.run.FightRecord) -> Boolean): String {
                    val sub = rs.filter(sel)
                    if (sub.isEmpty()) return "–"
                    val lost = sub.map { (it.hpBefore - it.hpAfter).toDouble() / it.maxHp }.avg()
                    val deaths = sub.count { !it.won }
                    return "${pct(lost)} · ${sub.size}" + if (deaths > 0) " · $deaths died" else ""
                }
                appendLine(
                    "| ${name(op)} | ${a.act} | ${cell { it.type == MomentType.COMBAT && it.threat == 1 }} | ${cell { it.type == MomentType.COMBAT && it.threat == 2 }} | " +
                        "${cell { it.type == MomentType.COMBAT && it.threat == 3 }} | ${cell { it.type == MomentType.ELITE }} | ${cell { it.type == MomentType.BOSS }} |",
                )
            }
        }
        appendLine()

        appendLine("## Bosses")
        appendLine()
        appendLine("Every boss fight, by encounter: how often it was won, HP lost in wins, and rounds.")
        appendLine()
        appendLine("| Boss | Operative | Fights | Won | HP lost (wins) | Rounds |")
        appendLine("|---|---|---|---|---|---|")
        val bossFights = byOp.mapValues { (_, st) -> st.flatMap { it.stats.fightRecords }.filter { it.type == MomentType.BOSS } }
        for (enc in bossFights.values.flatten().map { it.encounter }.distinct().sortedBy { id -> acts.indexOfFirst { a -> a.boss == id || id in a.bossByFlag.values || id in a.nexus.values } }) {
            for ((op, rs) in bossFights) {
                val sub = rs.filter { it.encounter == enc }
                if (sub.isEmpty()) continue
                val wins = sub.filter { it.won }
                appendLine(
                    "| ${encName(enc)} | ${name(op)} | ${sub.size} | ${pct(wins.size.toDouble() / sub.size)} | " +
                        "${pct(wins.map { (it.hpBefore - it.hpAfter).toDouble() / it.maxHp }.avg())} | ${num(sub.map { it.rounds.toDouble() }.avg())} |",
                )
            }
        }
        appendLine()

        appendLine("## Imprints and boss Artifacts")
        appendLine()
        appendLine("What the bot chose, per run.")
        appendLine()
        appendLine("| Operative | Imprints (most taken) | Boss Artifacts |")
        appendLine("|---|---|---|")
        for ((op, states) in byOp) {
            val imprints = states.flatMap { it.imprints }.groupingBy { it }.eachCount().entries.sortedByDescending { it.value }.take(6)
                .joinToString(", ") { "${re.rc.imprint(it.key).name} ${num(it.value.toDouble() / states.size, 2)}" }
            val boss = states.flatMap { s -> s.artifacts.filter { re.rc.artifact(it).boss } }.groupingBy { it }.eachCount().entries.sortedByDescending { it.value }
                .joinToString(", ") { "${re.rc.artifact(it.key).name} ${num(it.value.toDouble() / states.size, 2)}" }
            appendLine("| ${name(op)} | ${imprints.ifEmpty { "–" }} | ${boss.ifEmpty { "–" }} |")
        }
        appendLine()

        appendLine("## Time travel")
        appendLine()
        appendLine("| Operative | Returns dealt | Returns taken | Runs that Rewound | Rewinds per run | Won after a Rewind | Echoes fought | Anchor moves |")
        appendLine("|---|---|---|---|---|---|---|---|")
        for ((op, states) in byOp) {
            fun a(f: (RunState) -> Number) = num(states.map { f(it).toDouble() }.avg())
            val rewound = states.filter { it.stats.rewinds > 0 }
            val saved = rewound.count { won(it) }
            appendLine(
                "| ${name(op)} | ${a { it.stats.returnsDealt }} | ${a { it.stats.returnsTaken }} | ${pct(rewound.size.toDouble() / states.size)} | " +
                    "${a { it.stats.rewinds }} | ${if (rewound.isEmpty()) "–" else "$saved of ${rewound.size}"} | ${a { it.stats.echoesFought }} | ${a { it.stats.anchorMoves }} |",
            )
        }
        appendLine()

        appendLine("## Moments chosen")
        appendLine()
        val types = MomentType.entries.filter { it != MomentType.BOSS }
        appendLine("| Operative | " + types.joinToString(" | ") { it.label } + " |")
        appendLine("|---|" + types.joinToString("") { "---|" })
        for ((op, states) in byOp) {
            appendLine("| ${name(op)} | " + types.joinToString(" | ") { t -> num(states.map { (it.stats.chosen[t] ?: 0).toDouble() }.avg()) } + " |")
        }
        appendLine()

        appendLine("## Encounters")
        appendLine()
        appendLine("All operatives together, by act: fights, average share of max HP lost, and deaths.")
        appendLine()
        appendLine("| Act | Encounter | Fights | HP lost | Deaths |")
        appendLine("|---|---|---|---|---|")
        val all = byOp.values.flatten().flatMap { it.stats.fightRecords }
        for (a in acts) {
            for ((enc, rs) in all.filter { it.act == a.act }.groupBy { it.encounter }.toList().sortedByDescending { it.second.size }) {
                appendLine(
                    "| ${a.act} | ${encName(enc)} | ${rs.size} | ${pct(rs.map { (it.hpBefore - it.hpAfter).toDouble() / it.maxHp }.avg())} | " +
                        "${rs.count { !it.won }} |",
                )
            }
        }
    }
}
